static int bad;
static void fail(const char *what, const char *in, int base, long want, long got) {
    fprintf(stderr, "%s [\"%s\" base %d]: want %ld got %ld\n", what, in, base, want, got);
    bad++;
}

int main(void) {
    assert(RAND_MAX == 2147483647);
    for (unsigned i = 0; i < sizeof srows / sizeof srows[0]; i++) {
        const struct srow *r = &srows[i];
        char *sent = (char *)0x1, *e = sent;
        errno_slot = 0;
        long v = strtol(r->in, &e, r->base);
        long end = (e == sent) ? -1 : (long)(e - r->in);
        if (v != r->sval) fail("strtol value", r->in, r->base, r->sval, v);
        if (end != r->send) fail("strtol end", r->in, r->base, r->send, end);
        if (errno_slot != r->serr) fail("strtol errno", r->in, r->base, r->serr, errno_slot);

        e = sent; errno_slot = 0;
        unsigned long u = strtoul(r->in, &e, r->base);
        end = (e == sent) ? -1 : (long)(e - r->in);
        if (u != r->uval) fail("strtoul value", r->in, r->base, (long)r->uval, (long)u);
        if (end != r->uend) fail("strtoul end", r->in, r->base, r->uend, end);
        if (errno_slot != r->uerr) fail("strtoul errno", r->in, r->base, r->uerr, errno_slot);

        /* The long long forms are the same type here and must agree exactly. */
        e = sent; errno_slot = 0;
        long long ll = strtoll(r->in, &e, r->base);
        if ((long)ll != r->sval || errno_slot != r->serr || ((e == sent) ? -1L : (long)(e - r->in)) != r->send)
            fail("strtoll", r->in, r->base, r->sval, (long)ll);
        e = sent; errno_slot = 0;
        unsigned long long ull = strtoull(r->in, &e, r->base);
        if ((unsigned long)ull != r->uval || errno_slot != r->uerr || ((e == sent) ? -1L : (long)(e - r->in)) != r->uend)
            fail("strtoull", r->in, r->base, (long)r->uval, (long)ull);
    }
    /* A successful call leaves errno alone (it is only ever set on failure), and a NULL endptr is allowed. */
    errno_slot = 77;
    assert(strtol("5", (char **)0, 10) == 5 && errno_slot == 77);
    assert(strtoul("5", (char **)0, 10) == 5 && errno_slot == 77);

    /* rand/srand: glibc's additive feedback generator, 40 values per seed covering the lag wrap-around. */
    for (unsigned i = 0; i < sizeof rrows / sizeof rrows[0]; i++) {
        srand(rrows[i].seed);
        for (int k = 0; k < 40; k++) {
            int got = rand();
            if (got != rrows[i].vals[k]) {
                fprintf(stderr, "rand seed %u value %d: want %d got %d\n", rrows[i].seed, k, rrows[i].vals[k], got);
                bad++;
                break;
            }
        }
    }
    /* Reseeding restarts the sequence; an unseeded generator is the seed-1 sequence. */
    srand(5); int a = rand(); srand(5); assert(rand() == a);
    srand(1);
    unsigned long long sum = 0; int last = 0;
    for (int i = 0; i < 100000; i++) { last = rand(); sum += (unsigned)last; }
    assert(sum == 107345864261546ULL && last == 660658275);
    srand(2024);
    sum = 0;
    for (int i = 0; i < 100000; i++) sum += (unsigned)rand();
    assert(sum == 107268764639582ULL);

    /* abs family; the most negative value is its own absolute value (two's complement, as glibc). */
    assert(abs(-5) == 5 && abs(5) == 5 && abs(0) == 0 && abs(-2147483647 - 1) == -2147483647 - 1);
    assert(labs(-7L) == 7L && labs(7L) == 7L && labs(-9223372036854775807L - 1) == -9223372036854775807L - 1);
    assert(llabs(-9LL) == 9LL && llabs(-9223372036854775807LL - 1) == -9223372036854775807LL - 1);

    /* div family truncates toward zero; quot * den + rem == num. */
    div_t d = div(-7, 2);   assert(d.quot == -3 && d.rem == -1);
    d = div(7, -2);         assert(d.quot == -3 && d.rem == 1);
    d = div(7, 2);          assert(d.quot == 3 && d.rem == 1);
    d = div(-7, -2);        assert(d.quot == 3 && d.rem == -1);
    ldiv_t l = ldiv(-7L, 2L);   assert(l.quot == -3 && l.rem == -1);
    lldiv_t ll2 = lldiv(7LL, -2LL); assert(ll2.quot == -3 && ll2.rem == 1);
    assert(sizeof(div_t) == 8 && sizeof(ldiv_t) == 16 && sizeof(lldiv_t) == 16);

    /* atol/atoll mirror atoi at their width and stop at the first non-digit. */
    assert(atol("123abc") == 123 && atol(" -77") == -77 && atol("9223372036854775807") == 9223372036854775807L);
    assert(atoll("-42") == -42 && atoll("") == 0);

    assert(bad == 0);
    return 0;
}
