static int mismatch(unsigned row, const char *field, long want, long got) {
    fprintf(stderr, "strptime row %u (input \"%s\", format \"%s\"): %s want %ld got %ld\n", row, rows[row].in, rows[row].fmt,
            field, want, got);
    return 1;
}

int main(void) {
    int bad = 0;
    for (unsigned i = 0; i < sizeof rows / sizeof rows[0]; i++) {
        const struct row *r = &rows[i];
        struct tm t;
        memset(&t, 0, sizeof t);
        t.tm_sec = 41; t.tm_min = 42; t.tm_hour = 13; t.tm_mday = 17; t.tm_mon = 6; t.tm_year = 111;
        t.tm_wday = 3; t.tm_yday = 99; t.tm_isdst = 1; t.tm_gmtoff = 777; t.tm_zone = (const char *)0;
        char *end = strptime(r->in, r->fmt, &t);
        long got = end ? (long)(end - r->in) : -1L;
        if (got != r->consumed) bad += mismatch(i, "consumed", r->consumed, got);
        if (t.tm_sec != r->sec) bad += mismatch(i, "tm_sec", r->sec, t.tm_sec);
        if (t.tm_min != r->min) bad += mismatch(i, "tm_min", r->min, t.tm_min);
        if (t.tm_hour != r->hour) bad += mismatch(i, "tm_hour", r->hour, t.tm_hour);
        if (t.tm_mday != r->mday) bad += mismatch(i, "tm_mday", r->mday, t.tm_mday);
        if (t.tm_mon != r->mon) bad += mismatch(i, "tm_mon", r->mon, t.tm_mon);
        if (t.tm_year != r->year) bad += mismatch(i, "tm_year", r->year, t.tm_year);
        if (t.tm_wday != r->wday) bad += mismatch(i, "tm_wday", r->wday, t.tm_wday);
        if (t.tm_yday != r->yday) bad += mismatch(i, "tm_yday", r->yday, t.tm_yday);
        if (t.tm_isdst != r->isdst) bad += mismatch(i, "tm_isdst", r->isdst, t.tm_isdst);
        if (t.tm_gmtoff != r->gmtoff) bad += mismatch(i, "tm_gmtoff", r->gmtoff, t.tm_gmtoff);
    }
    assert(bad == 0);
    return 0;
}
